// 2D graphs with Plotly.
//
// "js" traces arrive as JavaScript compiled from SymPy; they are sampled here
// for the visible range, so zooming and panning stay smooth. Lines are split
// at the exact break points sent by the server (singularities, case
// boundaries, periodic families such as π/2 + kπ) and wherever the values
// jump, so no false vertical lines appear. "segments" traces (recursive
// functions) are sampled by the server and re-fetched for a new view.

const COLORS = ['#2f5bea', '#d6453d', '#1a9b5b', '#9b4dca', '#e08a00', '#0f8fa8', '#c2368f', '#6b7280'];
const MAX_CUTS = 4000;

function compile(js, vars = ['x']) {
  try {
    // The code is generated by the server from SymPy objects, never from raw input.
    // eslint-disable-next-line no-new-func
    const f = new Function(...vars, `"use strict"; return (${js});`);
    return (...args) => {
      try {
        const y = f(...args);
        if (typeof y === 'boolean') return y;
        return typeof y === 'number' && Number.isFinite(y) ? y : NaN;
      } catch {
        return NaN;
      }
    };
  } catch {
    return null;
  }
}

const PLANE_KINDS = new Set(['implicit', 'region']);
const GRID = 160;

function linspace(a, b, n) {
  const out = new Array(n);
  for (let i = 0; i < n; i++) out[i] = a + (b - a) * i / (n - 1);
  return out;
}

// Values of g(x, y) on a grid, with the cells next to a pole (a denominator
// changing sign) and the points outside `mask` left empty, so the zero contour
// isn't drawn across asymptotes or outside the allowed region.
function implicitGrid(g, poles, mask, xr, yr, n = GRID) {
  const xs = linspace(xr[0], xr[1], n), ys = linspace(yr[0], yr[1], n);
  const z = ys.map((y) => xs.map((x) => {
    const v = g(x, y);
    return Number.isFinite(v) ? v : null;
  }));
  for (const d of poles) {
    const s = ys.map((y) => xs.map((x) => Math.sign(d(x, y))));
    for (let j = 0; j < n; j++) {
      for (let i = 0; i < n; i++) {
        const here = s[j][i];
        if ((i + 1 < n && s[j][i + 1] !== here) || (j + 1 < n && s[j + 1][i] !== here)) {
          z[j][i] = null;
          if (i + 1 < n) z[j][i + 1] = null;
          if (j + 1 < n) z[j + 1][i] = null;
        }
      }
    }
  }
  if (mask) {
    for (let j = 0; j < n; j++) for (let i = 0; i < n; i++) if (mask(xs[i], ys[j]) !== true) z[j][i] = null;
  }
  return { xs, ys, z };
}

function regionGrid(pred, xr, yr, n = 180) {
  const xs = linspace(xr[0], xr[1], n), ys = linspace(yr[0], yr[1], n);
  const z = ys.map((y) => xs.map((x) => (pred(x, y) === true ? 1 : null)));
  return { xs, ys, z };
}

// Copies of periodic positions inside [x0, x1].
function tile(start, period, x0, x1, max = 400) {
  const out = [];
  if (!(period > 0)) return [start];
  let k = Math.ceil((x0 - start) / period);
  const kEnd = Math.floor((x1 - start) / period);
  if (kEnd - k > max) return out;
  for (; k <= kEnd; k++) out.push(start + k * period);
  return out;
}

function cutsFor(trace, x0, x1) {
  const cuts = [];
  for (const b of trace.breaks ?? []) if (b > x0 && b < x1) cuts.push(b);
  for (const [start, period] of trace.periodic ?? []) {
    if (!(period > 0)) continue;
    let k = Math.ceil((x0 - start) / period);
    const kEnd = Math.floor((x1 - start) / period);
    if (kEnd - k > MAX_CUTS) continue;  // zoomed far out: rely on jump detection
    for (; k <= kEnd; k++) cuts.push(start + k * period);
  }
  return [...new Set(cuts)].sort((a, b) => a - b);
}

// Robust y-extent of a set of samples (ignores blow-ups near asymptotes).
function robustSpan(ys, trim = 0.03) {
  const v = ys.filter((y) => y !== null && Number.isFinite(y)).sort((a, b) => a - b);
  if (!v.length) return null;
  const q = (p) => v[Math.min(v.length - 1, Math.max(0, Math.floor(p * (v.length - 1))))];
  let lo = q(trim), hi = q(1 - trim);
  if (hi - lo < 1e-9) { lo = v[0]; hi = v[v.length - 1]; }
  return [lo, hi];
}

// Sample f on [x0, x1], split at cuts, refine where the curve bends, break at jumps.
export function sampleFunction(f, trace, x0, x1, budget = 1200) {
  const width = x1 - x0;
  const eps = width * 1e-9;
  const cuts = cutsFor(trace, x0, x1);
  const edges = [x0, ...cuts, x1];
  const xs = [], ys = [];
  const pieces = [];
  for (let i = 0; i + 1 < edges.length; i++) {
    const a = i === 0 ? edges[i] : edges[i] + eps;
    const b = i + 2 === edges.length ? edges[i + 1] : edges[i + 1] - eps;
    if (b <= a) continue;
    const n = Math.max(6, Math.ceil(budget * (b - a) / width));
    const px = [], py = [];
    for (let j = 0; j <= n; j++) {
      const x = a + (b - a) * j / n;
      px.push(x);
      py.push(f(x));
    }
    pieces.push([px, py]);
  }
  // Estimate the visible span for the refinement and jump tests.
  const span = robustSpan(pieces.flatMap((p) => p[1]).map((y) => (Number.isFinite(y) ? y : null)));
  const ySpan = span ? Math.max(span[1] - span[0], 1e-6) : 1;
  const tol = ySpan / 600;
  for (const [px, py] of pieces) {
    // Refinement passes: insert midpoints where the curve deviates from a straight line.
    let X = px, Y = py;
    for (let pass = 0; pass < 5; pass++) {
      const nx = [X[0]], ny = [Y[0]];
      let changed = false;
      for (let j = 0; j + 1 < X.length; j++) {
        const xa = X[j], xb = X[j + 1], ya = Y[j], yb = Y[j + 1];
        const both = Number.isFinite(ya) && Number.isFinite(yb);
        const either = Number.isFinite(ya) || Number.isFinite(yb);
        if (either && (xb - xa) > width * 1e-7) {
          const xm = (xa + xb) / 2;
          const ym = f(xm);
          const dev = both && Number.isFinite(ym) ? Math.abs(ym - (ya + yb) / 2) : Infinity;
          if (dev > tol && nx.length < 20000) {
            nx.push(xm); ny.push(ym); changed = true;
          }
        }
        nx.push(xb); ny.push(yb);
      }
      X = nx; Y = ny;
      if (!changed) break;
    }
    // Break the line at jumps: a large step whose midpoint isn't between its ends.
    for (let j = 0; j < X.length; j++) {
      if (j > 0) {
        const ya = Y[j - 1], yb = Y[j];
        if (Number.isFinite(ya) && Number.isFinite(yb) && Math.abs(yb - ya) > ySpan * 0.5) {
          const ym = f((X[j - 1] + X[j]) / 2);
          const between = Number.isFinite(ym) && ym >= Math.min(ya, yb) - tol && ym <= Math.max(ya, yb) + tol;
          if (!between) { xs.push(null); ys.push(null); }
        }
      }
      xs.push(X[j]);
      ys.push(Number.isFinite(Y[j]) ? Y[j] : null);
    }
    xs.push(null); ys.push(null);  // separate pieces at break points
  }
  return { xs, ys };
}

function segmentsToXY(segments) {
  const xs = [], ys = [];
  for (const s of segments ?? []) {
    for (let i = 0; i < s.x.length; i++) {
      xs.push(s.x[i]);
      ys.push(s.y[i] === null || !Number.isFinite(s.y[i]) ? null : s.y[i]);
    }
    xs.push(null); ys.push(null);
  }
  return { xs, ys };
}

function cssVar(name, fallback) {
  const v = getComputedStyle(document.documentElement).getPropertyValue(name).trim();
  return v || fallback;
}

// Roots of g(x) = level on [x0, x1]: sign changes on a grid (not across poles), refined by
// bisection, plus touching points (a local minimum of |g - level| that reaches 0).
function levelRoots(g, level, x0, x1, n = 1500) {
  const out = [];
  const h = (x) => g(x) - level;
  const tol = 1e-7 * Math.max(1, Math.abs(level));
  const xs = [], ys = [];
  for (let j = 0; j <= n; j++) { xs.push(x0 + (x1 - x0) * j / n); ys.push(h(xs[j])); }
  for (let j = 0; j < n; j++) {
    const ya = ys[j], yb = ys[j + 1];
    if (!Number.isFinite(ya) || !Number.isFinite(yb)) continue;
    if (ya === 0) { out.push(xs[j]); continue; }
    if (ya * yb < 0) {
      let u = xs[j], w = xs[j + 1], yu = ya;
      for (let k = 0; k < 50; k++) {
        const m = (u + w) / 2, ym = h(m);
        if (!Number.isFinite(ym)) { u = NaN; break; }
        if ((ym < 0) === (yu < 0)) { u = m; yu = ym; } else w = m;
      }
      const r = (u + w) / 2;
      if (Number.isFinite(r) && Math.abs(h(r)) < 1e-6 * Math.max(1, Math.abs(level))) out.push(r);
    } else if (j > 0 && Number.isFinite(ys[j - 1]) && ys[j - 1] * ya > 0
               && Math.abs(ya) <= Math.abs(ys[j - 1]) && Math.abs(ya) <= Math.abs(yb)) {
      let u = xs[j - 1], w = xs[j + 1];
      for (let k = 0; k < 80; k++) {  // golden-section search for the smallest |h|
        const m1 = u + (w - u) * 0.382, m2 = u + (w - u) * 0.618;
        if (Math.abs(h(m1)) < Math.abs(h(m2))) w = m2; else u = m1;
      }
      const r = (u + w) / 2;
      if (Math.abs(h(r)) < tol) out.push(r);
    }
  }
  return out;
}

// A round slider step (1, 2 or 5 times a power of ten) giving about 200 positions.
function niceStep(span) {
  const raw = span / 200;
  const p = 10 ** Math.floor(Math.log10(raw));
  return [1, 2, 5, 10].map((m) => m * p).find((s) => s >= raw) ?? raw;
}

export class GraphView {
  // refetch(xRange) -> Promise<graph spec> (for traces sampled by the server)
  constructor(container, spec, { refetch } = {}) {
    this.container = container;
    this.spec = spec;
    this.refetch = refetch;
    this.vars = spec.vars ?? [spec.var ?? 'x', 'y'];
    // Sliders: every compiled function also takes the parameters, read at call time.
    this.params = spec.params ?? [];
    this.pv = this.params.map((p) => p.value);
    const make = (js, vars) => {
      // A parameter that is also a plotted variable (a in the (x, a) plane) takes the grid's value.
      const idx = this.params.map((p, i) => (vars.includes(p.name) ? -1 : i)).filter((i) => i >= 0);
      const f = compile(js, [...vars, ...idx.map((i) => this.params[i].name)]);
      return f && (idx.length ? (...args) => f(...args, ...idx.map((i) => this.pv[i])) : f);
    };
    this.fns = spec.traces.map((t) => {
      if ((t.kind === 'js' || t.kind === 'area') && t.js) return make(t.js, [this.vars[0]]);
      if (PLANE_KINDS.has(t.kind) && t.js) return make(t.js, t.vars ?? this.vars);
      if (t.kind === 'points' && t.y_js) return make(t.y_js, [this.vars[0]]);
      if (t.kind === 'levelroots') return (t.js ?? []).map((g) => make(g, [this.vars[0]])).filter(Boolean);
      if (t.kind === 'surface' && t.js) return make(t.js, ['x', 'y']);
      return null;
    });
    this.extra = spec.traces.map((t) => ({
      poles: (t.poles ?? []).map((p) => make(p, t.vars ?? this.vars)).filter(Boolean),
      mask: t.mask ? make(t.mask, t.vars ?? this.vars) : null,
    }));
    this.plane = spec.traces.some((t) => PLANE_KINDS.has(t.kind)) || Boolean(spec.vars);
    this.range = [...spec.x_range];
    this.yRange = spec.y_range ? [...spec.y_range] : null;
    this.timer = null;
    this.fetchTimer = null;
    this.fetchSeq = 0;
  }

  data() {
    const bg = cssVar('--panel', '#ffffff');
    const out = [];
    // With equal axis scales Plotly may widen a range: sample what is really shown.
    const full = this.container._fullLayout;
    const yr = (this.plane && full?.yaxis?.range) || this.yRange || this.container.layout?.yaxis?.range || [-10, 10];
    const xr = (this.plane && full?.xaxis?.range) || this.range;
    let colorIndex = 0;
    this.spec.traces.forEach((t, i) => {
      if (t.kind === 'xbands' || t.kind === 'vlines') return;  // drawn as layout shapes
      if (t.kind === 'area') {
        // Shaded area between the curve and the x-axis over [from, to] (an integral).
        const f = this.fns[i];
        if (!f) return;
        const a = Math.max(t.from ?? -Infinity, xr[0]);
        const b = Math.min(t.to ?? Infinity, xr[1]);
        if (!(b > a)) return;
        const n = 400, xs = [a], ys = [0];
        for (let j = 0; j <= n; j++) {
          const xv = a + (b - a) * j / n;
          const yv = f(xv);
          xs.push(xv); ys.push(Number.isFinite(yv) ? yv : 0);
        }
        xs.push(b); ys.push(0);
        out.push({
          type: 'scatter', mode: 'lines', x: xs, y: ys, fill: 'toself', fillcolor: 'rgba(47, 91, 234, 0.22)',
          line: { width: 0 }, hoverinfo: 'skip', name: t.label, showlegend: false,
        });
        return;
      }
      const color = t.kind === 'region' ? COLORS[0] : COLORS[colorIndex++ % COLORS.length];
      const f = this.fns[i];
      if (t.kind === 'region') {
        if (!f) return;
        const { xs, ys, z } = regionGrid(f, xr, yr);
        out.push({
          type: 'heatmap', x: xs, y: ys, z, zmin: 0, zmax: 1, showscale: false, hoverinfo: 'skip',
          colorscale: [[0, color], [1, color]], opacity: 0.22, name: t.label, showlegend: false, zsmooth: false,
        });
        return;
      }
      if (t.kind === 'implicit') {
        if (!f) return;
        const { xs, ys, z } = implicitGrid(f, this.extra[i].poles, this.extra[i].mask, xr, yr);
        out.push({
          type: 'contour', x: xs, y: ys, z, name: t.label, showscale: false, hoverinfo: 'skip',
          autocontour: false, contours: { start: 0, end: 0, size: 1, coloring: 'lines', showlabels: false },
          colorscale: [[0, color], [1, color]],
          line: { color, width: t.faint ? 1.4 : 2.4, dash: t.dash ? 'dash' : 'solid' },
          connectgaps: false, showlegend: true,
        });
        return;
      }
      if (t.kind === 'levelroots') {
        // Where the horizontal line at the slider's level meets the curves.
        const level = this.pv[this.params.findIndex((p) => p.name === t.param)];
        if (!Number.isFinite(level)) return;
        const xs = [];
        for (const g of f ?? []) xs.push(...levelRoots(g, level, xr[0], xr[1]));
        for (const c of t.always ?? []) if (c >= xr[0] && c <= xr[1]) xs.push(c);
        const ink = cssVar('--text', '#1d2330');
        out.push({
          type: 'scatter', mode: 'markers', x: xs, y: xs.map(() => level), name: t.label,
          marker: { color: COLORS[1], size: 10, line: { color: ink, width: 1 } },
          hovertemplate: `${t.label}<br>x ≈ %{x:.5g}<extra></extra>`,
        });
        return;
      }
      if (t.kind === 'points') {
        const xs = [], ys = [], text = [];
        const add = (x, y, label) => {
          if (!Number.isFinite(x) || !Number.isFinite(y)) return;
          xs.push(x); ys.push(y); text.push(label);
        };
        (t.x ?? []).forEach((x, j) => add(x, t.y ? t.y[j] : (f ? f(x) : 0), t.text?.[j] ?? ''));
        for (const [start, period] of t.periodic ?? []) {
          for (const x of tile(start, period, this.range[0], this.range[1])) add(x, f ? f(x) : 0, x.toPrecision(5));
        }
        const ink = cssVar('--text', '#1d2330');
        out.push({
          type: 'scatter', mode: 'markers', x: xs, y: ys, text, name: t.label,
          marker: t.open ? { color: bg, size: 10, line: { color: ink, width: 2 } } : { color: ink, size: 9, symbol: 'circle' },
          hovertemplate: `${t.label}<br>%{text}<extra></extra>`,
        });
        return;
      }
      const { xs, ys } = f ? sampleFunction(f, t, xr[0], xr[1]) : segmentsToXY(t.segments);
      out.push({
        type: 'scatter', mode: 'lines', x: xs, y: ys, name: t.label, connectgaps: false,
        line: { color, width: t.faint ? 1.4 : 2.4, dash: t.dash ? 'dash' : 'solid' },
        hovertemplate: `${t.label}<br>x=%{x:.4g}<br>y=%{y:.4g}<extra></extra>`,
      });
      const closed = (t.dots ?? []).filter((d) => !d.open);
      const open = (t.dots ?? []).filter((d) => d.open);
      if (closed.length) {
        out.push({
          type: 'scatter', mode: 'markers', x: closed.map((d) => d.x), y: closed.map((d) => d.y),
          marker: { color, size: 9, line: { color, width: 2 } }, showlegend: false,
          hovertemplate: `${t.label}<br>(%{x:.6g}, %{y:.6g}) included<extra></extra>`,
        });
      }
      if (open.length) {
        out.push({
          type: 'scatter', mode: 'markers', x: open.map((d) => d.x), y: open.map((d) => d.y),
          marker: { color: bg, size: 9, line: { color, width: 2 } }, showlegend: false,
          hovertemplate: `${t.label}<br>(%{x:.6g}, %{y:.6g}) not included<extra></extra>`,
        });
      }
    });
    return out;
  }

  // Shaded x-intervals (one-variable inequalities), tiled when periodic; vertical asymptotes.
  shapes() {
    const out = [];
    const color = COLORS[0];
    for (const t of this.spec.traces) {
      if (t.kind === 'vlines') {
        const xs = [...(t.x ?? [])];
        for (const [start, period] of t.periodic ?? []) xs.push(...tile(start, period, this.range[0], this.range[1]));
        for (const xv of xs) {
          out.push({
            type: 'line', xref: 'x', yref: 'paper', x0: xv, x1: xv, y0: 0, y1: 1, layer: 'below',
            line: { color: cssVar('--muted', '#6b7280'), width: 1.4, dash: 'dash' },
          });
        }
        continue;
      }
      if (t.kind !== 'xbands') continue;
      for (const [lo, hi] of t.intervals ?? []) {
        const starts = t.period ? tile(lo ?? hi, t.period, this.range[0] - t.period, this.range[1] + t.period) : [lo ?? hi];
        for (const s0 of starts) {
          const shift = s0 - (lo ?? hi);
          out.push({
            type: 'rect', xref: 'x', yref: 'paper', y0: 0, y1: 1, layer: 'below', line: { width: 0 },
            x0: lo === null ? this.range[0] - (this.range[1] - this.range[0]) : lo + shift,
            x1: hi === null ? this.range[1] + (this.range[1] - this.range[0]) : hi + shift,
            fillcolor: color, opacity: 0.12,
          });
        }
      }
    }
    return out;
  }

  initialYRange() {
    if (this.spec.y_range) return this.spec.y_range;
    if (this.plane) return [...this.spec.x_range];  // curves and regions in x and y: same scale on both axes
    // A plain uniform sample (refinement crowds points near asymptotes and would
    // stretch the range), trimmed to the middle 90% of values.
    const [x0, x1] = this.range;
    const ys = [];
    this.spec.traces.forEach((t, i) => {
      if (t.kind !== 'js' && t.kind !== 'segments') return;
      const f = this.fns[i];
      if (f) for (let j = 0; j <= 400; j++) ys.push(f(x0 + (x1 - x0) * j / 400));
      else for (const seg of t.segments ?? []) ys.push(...seg.y.filter((y) => y !== null));
    });
    const dots = this.spec.traces.flatMap((t) => (t.dots ?? []).map((d) => d.y));
    let span = robustSpan(ys.map((y) => (Number.isFinite(y) ? y : null)), 0.05);
    if (!span) return [-5, 5];
    let [lo, hi] = span;
    for (const d of dots) { lo = Math.min(lo, d); hi = Math.max(hi, d); }
    if (hi - lo < 1e-9) { lo -= 1; hi += 1; }
    const pad = (hi - lo) * 0.2;
    return [lo - pad, hi + pad];
  }

  layout(yRange) {
    const text = cssVar('--text', '#1d2330');
    const grid = cssVar('--border', '#dde1e8');
    const axis = (range, title) => ({
      range, title: { text: title }, zeroline: true, zerolinecolor: text, zerolinewidth: 1.2,
      gridcolor: grid, color: text, automargin: true,
    });
    const yaxis = axis(yRange, this.vars[1] ?? 'y');
    if (this.plane && !this.spec.free_aspect) {
      yaxis.scaleanchor = 'x';  // circles look round
      yaxis.scaleratio = 1;
    }
    return {
      xaxis: axis(this.range, this.vars[0] ?? 'x'), yaxis,
      margin: { l: 50, r: 16, t: 30, b: 40 }, height: 440, dragmode: 'pan', hovermode: 'closest',
      paper_bgcolor: 'rgba(0,0,0,0)', plot_bgcolor: 'rgba(0,0,0,0)', font: { color: text },
      legend: { orientation: 'h', x: 0, y: 1.08 }, showlegend: true, uirevision: 'keep',
      shapes: this.shapes(),
    };
  }

  async render() {
    const Plotly = window.Plotly;
    if (!Plotly) {
      this.container.textContent = 'The plotting library did not load.';
      return;
    }
    const y0 = this.initialYRange();
    if (this.plane && !this.yRange) this.yRange = [...y0];
    if (this.params.length) this.buildSliders();
    const traces = this.data();
    await Plotly.newPlot(this.container, traces, this.layout(y0), {
      responsive: true, scrollZoom: true, displaylogo: false,
      modeBarButtonsToRemove: ['lasso2d', 'select2d', 'autoScale2d'],
    });
    this.container.on('plotly_relayout', (ev) => this.onRelayout(ev));
    if (this.plane) this.redraw();  // re-sample regions for the ranges Plotly actually chose
  }

  // One row per parameter: name, slider, value box, and editable ends of the range.
  buildSliders() {
    const panel = document.createElement('div');
    panel.className = 'sliders';
    const input = (cls, value, title) => {
      const e = document.createElement('input');
      e.type = 'text'; e.className = cls; e.value = String(value); e.title = title; e.spellcheck = false;
      return e;
    };
    this.params.forEach((p, i) => {
      const row = document.createElement('div');
      row.className = 'slider-row';
      const name = document.createElement('span');
      name.className = 'pname'; name.textContent = p.name;
      const lo = input('bound', p.min, `smallest ${p.name}`);
      const hi = input('bound', p.max, `largest ${p.name}`);
      const range = document.createElement('input');
      const step = niceStep(p.max - p.min);
      // Ends on multiples of the step, so round values such as a critical a = 1 can be reached.
      range.type = 'range'; range.step = step;
      const snap = (v) => Number((Math.round(v / step) * step).toPrecision(12));
      range.min = Math.min(snap(p.min), p.value); range.max = Math.max(snap(p.max), p.value);
      range.value = p.value;
      lo.value = range.min; hi.value = range.max;
      range.setAttribute('aria-label', `parameter ${p.name}`);
      const box = input('value', p.value, `value of ${p.name}`);
      const set = (v, fromBox = false) => {
        if (!Number.isFinite(v)) return;
        this.pv[i] = v;
        if (!fromBox) box.value = String(Number(v.toPrecision(6)));
        if (fromBox && (v < Number(range.min) || v > Number(range.max))) {
          range.min = Math.min(v, Number(range.min)); range.max = Math.max(v, Number(range.max));
          lo.value = range.min; hi.value = range.max;
        }
        range.value = v;
        this.scheduleRedraw();
      };
      range.addEventListener('input', () => set(Number(range.value)));
      box.addEventListener('change', () => set(Number(box.value), true));
      const bound = (el, key) => el.addEventListener('change', () => {
        const v = Number(el.value);
        if (!Number.isFinite(v)) { el.value = range[key]; return; }
        range[key] = v;
        range.step = niceStep(Number(range.max) - Number(range.min));
        set(Number(range.value));
      });
      bound(lo, 'min'); bound(hi, 'max');
      row.append(name, lo, range, hi, box);
      panel.append(row);
    });
    if (this.spec.readout) {
      this.readoutBox = document.createElement('div');
      this.readoutBox.className = 'readout';
      panel.append(this.readoutBox);
    }
    this.container.parentNode?.insertBefore(panel, this.container);
    this.updateReadout();
  }

  scheduleRedraw() {
    if (this.frame) return;
    this.frame = requestAnimationFrame(() => {
      this.frame = null;
      this.redraw();
      this.updateReadout();
    });
  }

  // "a = 0.5: 2 solutions" from the table the server sent (rows of the a-line).
  updateReadout() {
    const r = this.spec.readout;
    if (!r || !this.readoutBox) return;
    const v = this.pv[this.params.findIndex((p) => p.name === r.param)];
    const inside = (row) => {
      const near = (u) => Math.abs(v - u) <= 1e-9 * Math.max(1, Math.abs(u));
      if (row.at !== undefined && row.at !== null) return near(row.at);
      return (row.lo === null || v > row.lo || (row.lo_closed && near(row.lo)))
        && (row.hi === null || v < row.hi || (row.hi_closed && near(row.hi)));
    };
    const row = r.rows.find((w) => w.at !== undefined && w.at !== null && inside(w)) ?? r.rows.find(inside);
    this.readoutBox.textContent = `${r.param} = ${Number(v.toPrecision(6))}: ${row ? row.text : '?'}`;
  }

  onRelayout(ev) {
    let range = null;
    if (ev['xaxis.range[0]'] !== undefined) range = [ev['xaxis.range[0]'], ev['xaxis.range[1]']];
    else if (Array.isArray(ev['xaxis.range'])) range = ev['xaxis.range'];
    else if (ev['xaxis.autorange']) range = [...this.spec.x_range];
    if (this.plane) {
      // Regions and implicit curves depend on the y range too.
      const yr = this.container.layout?.yaxis?.range;
      if (ev['yaxis.autorange'] || ev['xaxis.autorange']) this.yRange = this.spec.y_range ? [...this.spec.y_range] : null;
      else if (Array.isArray(yr)) this.yRange = yr.map(Number);
      if (!range) range = this.container.layout?.xaxis?.range ?? null;
    }
    if (!range) return;
    range = range.map(Number);
    if (!(range[1] > range[0])) return;
    this.range = range;
    clearTimeout(this.timer);
    this.timer = setTimeout(() => this.redraw(ev['xaxis.autorange'] ? this.initialYRange() : null), 60);
    if (this.refetch && this.spec.traces.some((t) => t.refetch)) {
      clearTimeout(this.fetchTimer);
      this.fetchTimer = setTimeout(() => this.fetchRange(range), 350);
    }
  }

  redraw(yRange = null) {
    const layout = this.container.layout;
    if (this.plane && yRange) this.yRange = [...yRange];
    const traces = this.data();
    const y = yRange ?? (this.plane && this.yRange ? this.yRange : layout.yaxis.range);
    window.Plotly.react(this.container, traces, { ...this.layout(y), xaxis: { ...this.layout(y).xaxis, range: this.range } });
  }

  async fetchRange(range) {
    const seq = ++this.fetchSeq;
    let spec;
    try {
      spec = await this.refetch(range);
    } catch {
      return;
    }
    if (seq !== this.fetchSeq || !spec?.traces) return;
    this.spec.traces.forEach((t, i) => {
      const fresh = spec.traces[i];
      if (t.refetch && fresh && fresh.label === t.label) {
        t.segments = fresh.segments;
        t.dots = fresh.dots;
        t.breaks = fresh.breaks;
      }
    });
    this.redraw();
  }
}

// Surfaces z = f(x, y): sampled on a grid in the browser, rotatable; sliders redraw them in place.
const SURFACE_GRID = 72;

function lighten(hex, amount) {
  const n = parseInt(hex.slice(1), 16);
  const mix = (c) => Math.round(c + (255 - c) * amount);
  return `rgb(${mix(n >> 16)}, ${mix((n >> 8) & 255)}, ${mix(n & 255)})`;
}

// "2", "-1.5", "pi", "2pi", "-pi/2" -> number (NaN if not understood).
function parseBound(text) {
  const s = String(text).trim().toLowerCase().replace(/π/g, 'pi').replace(/\s+/g, '');
  if (s === '') return NaN;
  const m = s.match(/^([+-]?\d*\.?\d*)\*?pi(?:\/(\d+\.?\d*))?$/);
  if (m) {
    const k = m[1] === '' || m[1] === '+' ? 1 : m[1] === '-' ? -1 : Number(m[1]);
    return k * Math.PI / (m[2] ? Number(m[2]) : 1);
  }
  return s.match(/^[+-]?(\d+\.?\d*|\.\d+)(e[+-]?\d+)?$/) ? Number(s) : NaN;
}

const short = (v) => String(Number(v.toPrecision(4)));

class SurfaceView extends GraphView {
  constructor(container, spec, options) {
    super(container, spec, options);
    this.zRange = null;
    this.xr = [...spec.x_range];
    this.yr = [...spec.y_range];
    this.zFixed = null;      // a z range typed by the user (otherwise automatic)
    this.clipSpikes = true;  // automatic z range: cut off the tallest 2% (poles)
    this.trueScale = false;  // false: drawn in a cube; true: x, y and z on the same scale
  }

  data() {
    const [x0, x1] = this.xr, [y0, y1] = this.yr;
    const xs = linspace(x0, x1, SURFACE_GRID), ys = linspace(y0, y1, SURFACE_GRID);
    const grids = this.spec.traces.map((t, i) => {
      const f = this.fns[i];
      return f ? ys.map((y) => xs.map((x) => f(x, y))) : null;
    });
    const all = grids.flatMap((g) => (g ? g.flat() : [])).filter(Number.isFinite).sort((a, b) => a - b);
    let lo = -1, hi = 1;
    if (this.zFixed) {
      [lo, hi] = this.zFixed;
    } else if (all.length) {
      lo = all[0]; hi = all[all.length - 1];
      if (this.clipSpikes) {
        // Clip blow-ups (poles) so they don't flatten the rest of the surface.
        const q = (p) => all[Math.min(all.length - 1, Math.floor(p * (all.length - 1)))];
        const pad = Math.max(q(0.98) - q(0.02), 1e-6) * 0.35;
        lo = Math.max(lo, q(0.02) - pad); hi = Math.min(hi, q(0.98) + pad);
      }
      if (hi - lo < 1e-9) { lo -= 1; hi += 1; }
    }
    this.zRange = [lo, hi];
    this.syncScaleFields?.();
    // Plotly cuts the surface cleanly at the z range; only values far outside it (poles) are
    // left out, so they can't distort the drawing.
    const span = hi - lo;
    return this.spec.traces.map((t, i) => {
      const g = grids[i];
      if (!g) return null;
      const z = g.map((row) => row.map((v) => (Number.isFinite(v) && v >= lo - 10 * span && v <= hi + 10 * span ? v : null)));
      const color = COLORS[i % COLORS.length];
      return {
        type: 'surface', x: xs, y: ys, z, name: t.label, showscale: false, opacity: this.spec.traces.length > 1 ? 0.85 : 1,
        cmin: lo, cmax: hi,
        colorscale: i === 0 ? 'Viridis' : [[0, lighten(color, 0.6)], [1, color]],
        contours: { z: { show: true, usecolormap: true, highlightcolor: '#ffffff', project: { z: false } } },
        hovertemplate: `${t.label}<br>x=%{x:.4g}<br>y=%{y:.4g}<br>z=%{z:.4g}<extra></extra>`,
      };
    }).filter(Boolean);
  }

  layout() {
    const text = cssVar('--text', '#1d2330');
    const grid = cssVar('--border', '#dde1e8');
    const axis = (title, range) => ({ title: { text: title }, gridcolor: grid, color: text, range, zerolinecolor: text });
    return {
      scene: {
        xaxis: axis('x', this.xr), yaxis: axis('y', this.yr), zaxis: axis('z', this.zRange),
        aspectmode: this.trueScale ? 'data' : 'cube', camera: { eye: { x: 1.3, y: -1.3, z: 0.95 } },
      },
      margin: { l: 0, r: 0, t: 30, b: 0 }, height: 580, paper_bgcolor: 'rgba(0,0,0,0)',
      font: { color: text }, showlegend: this.spec.traces.length > 1, legend: { orientation: 'h', x: 0, y: 1.05 },
      uirevision: 'keep',  // keep the user's rotation when a slider or a range changes
    };
  }

  // x, y and z ranges, zoom buttons and display switches above the 3D graph.
  buildScaleControls() {
    const panel = document.createElement('div');
    panel.className = 'scale-panel';
    const fields = {};
    const range = (axis, auto) => {
      const box = document.createElement('span');
      box.className = 'scale-range';
      const name = document.createElement('span');
      name.className = 'pname';
      name.textContent = axis;
      const mk = (end) => {
        const e = document.createElement('input');
        e.type = 'text'; e.spellcheck = false; e.className = 'bound';
        e.title = `${end === 0 ? 'smallest' : 'largest'} ${axis}${auto ? ' (empty = automatic)' : ''}`;
        if (auto) e.placeholder = 'auto';
        e.addEventListener('change', () => this.applyScaleFields());
        e.addEventListener('keydown', (ev) => { if (ev.key === 'Enter') this.applyScaleFields(); });
        return e;
      };
      fields[axis] = [mk(0), mk(1)];
      const to = document.createElement('span');
      to.textContent = 'to';
      box.append(name, fields[axis][0], to, fields[axis][1]);
      return box;
    };
    const button = (label, title, fn) => {
      const b = document.createElement('button');
      b.type = 'button'; b.className = 'scale-btn'; b.textContent = label; b.title = title;
      b.addEventListener('click', fn);
      return b;
    };
    const toggle = (label, title, get, set) => {
      const l = document.createElement('label');
      l.className = 'scale-toggle'; l.title = title;
      const c = document.createElement('input');
      c.type = 'checkbox'; c.checked = get();
      c.addEventListener('change', () => { set(c.checked); this.scheduleRedraw(); });
      l.append(c, document.createTextNode(' ' + label));
      return l;
    };
    const zoom = (factor) => {
      const scale = ([a, b]) => { const m = (a + b) / 2, h = (b - a) / 2 * factor; return [m - h, m + h]; };
      this.xr = scale(this.xr); this.yr = scale(this.yr);
      if (this.zFixed) this.zFixed = scale(this.zFixed);
      this.scheduleRedraw();
    };
    panel.append(
      range('x'), range('y'), range('z', true),
      button('Zoom out', 'Show twice as much of x and y', () => zoom(2)),
      button('Zoom in', 'Show half as much of x and y', () => zoom(0.5)),
      button('Reset', 'Back to the starting view', () => {
        this.xr = [...this.spec.x_range]; this.yr = [...this.spec.y_range]; this.zFixed = null;
        for (const el of fields.z) el.value = '';
        panel.classList.remove('invalid');
        this.scheduleRedraw();
      }),
      toggle('cut off spikes', 'With an automatic z range, leave out the tallest 2% of values (near poles)',
        () => this.clipSpikes, (v) => { this.clipSpikes = v; }),
      toggle('true proportions', 'Draw x, y and z to the same scale instead of in a cube',
        () => this.trueScale, (v) => { this.trueScale = v; }),
    );
    this.scaleFields = fields;
    this.scalePanel = panel;
    this.container.parentNode?.insertBefore(panel, this.container);
  }

  // Show the current ranges in the boxes. A typed z range stays as typed; an automatic one
  // shows its values in grey (as placeholders), so the boxes are never overwritten under the user.
  syncScaleFields() {
    const f = this.scaleFields;
    if (!f) return;
    const put = (el, v) => { if (document.activeElement !== el) el.value = short(v); };
    put(f.x[0], this.xr[0]); put(f.x[1], this.xr[1]); put(f.y[0], this.yr[0]); put(f.y[1], this.yr[1]);
    if (this.zFixed) {
      put(f.z[0], this.zFixed[0]); put(f.z[1], this.zFixed[1]);
    } else if (this.zRange) {
      f.z[0].placeholder = short(this.zRange[0]); f.z[1].placeholder = short(this.zRange[1]);
    }
  }

  applyScaleFields() {
    const f = this.scaleFields;
    const read = ([a, b]) => [parseBound(a.value), parseBound(b.value)];
    const ok = ([a, b]) => Number.isFinite(a) && Number.isFinite(b) && b > a;
    const x = read(f.x), y = read(f.y), z = read(f.z);
    let bad = false;
    if (ok(x)) this.xr = x; else bad = true;
    if (ok(y)) this.yr = y; else bad = true;
    const zFilled = f.z.map((el) => el.value.trim() !== '');
    if (!zFilled[0] && !zFilled[1]) this.zFixed = null;
    else if (zFilled[0] && zFilled[1]) {
      if (ok(z)) this.zFixed = z; else bad = true;
    }  // only one z box filled: wait for the other
    this.scalePanel.classList.toggle('invalid', bad);
    this.scalePanel.title = bad ? 'Each range needs two numbers, the first smaller (pi and 2pi work).' : '';
    this.scheduleRedraw();
  }

  async render() {
    const Plotly = window.Plotly;
    if (!Plotly) {
      this.container.textContent = 'The plotting library did not load.';
      return;
    }
    if (this.params.length) this.buildSliders();
    this.buildScaleControls();
    const traces = this.data();
    await Plotly.newPlot(this.container, traces, this.layout(), { responsive: true, displaylogo: false });
  }

  redraw() {
    const traces = this.data();
    window.Plotly.react(this.container, traces, this.layout());
  }
}

const views = new Set();

export function renderGraph(container, spec, options) {
  const view = spec.three_d ? new SurfaceView(container, spec, options) : new GraphView(container, spec, options);
  view.render();
  views.add(view);
  return view;
}

// After a theme change: redraw every graph still on the page (colours are read when drawing).
export function redrawAllGraphs() {
  for (const v of [...views]) {
    if (!v.container.isConnected) { views.delete(v); continue; }
    if (v.container.data) v.redraw();
  }
}
